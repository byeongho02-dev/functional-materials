import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = await readFile(new URL('../ale-v092-fab-preview.html', import.meta.url), 'utf8');
const css = await readFile(new URL('../src/fab3d/style.css', import.meta.url), 'utf8');
const license = await readFile(new URL('../docs/fab3d/THREE-LICENSE.txt', import.meta.url), 'utf8');
const cssTag = '<link rel="stylesheet" href="/src/fab3d/style.css">';
const scriptTag = '<script type="module" src="/src/fab3d/main.js"></script>';
if (!source.includes(cssTag) || !source.includes(scriptTag)) {
  throw new Error('Preview template entry points changed; update the static-page builder.');
}
const bundled = await build({
  absWorkingDir: root,
  entryPoints: ['src/fab3d/main.js'],
  bundle: true,
  minify: true,
  format: 'iife',
  platform: 'browser',
  legalComments: 'inline',
  write: false,
});
const javascript = bundled.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const html = source
  .replace('<head>', () => '<head>\n<!-- Generated by npm run build:fab:static. Edit src/fab3d/ and the preview template. -->\n<!-- Three.js 0.182.0 — MIT license\n' + license + '-->')
  .replace(cssTag, () => '<style>\n' + css + '\n</style>')
  .replace(scriptTag, () => '<script>\n' + javascript + '\n</script>')
  .replace('Production-style ICP · ALE V0.9.2 Preview', 'Production-style ICP · ALE V0.9.2')
  .replace('REVIEW PREVIEW', 'CONCEPT MODEL');
await writeFile(new URL('../ale-v092-fab.html', import.meta.url), html);
console.log('Built ale-v092-fab.html (' + Buffer.byteLength(html) + ' bytes; no runtime CDN or npm imports).');
